//! # Stock Stalker
//!
//! Библиотека для потоковой передачи котировок акций по протоколу TCP/UDP с поддержкой heartbeat-механизма.
//!
//! ## Описание
//!
//! Проект реализует сервер для рассылки котировок акций по подписке. Сервер принимает команды через TCP-соединение,
//! а отправка котировок происходит по UDP. Для контроля активности подписчиков используется механизм heartbeat
//! (PING/PONG).
//!
//! ## Архитектура
//!
//! - **TCP сервер** - принимает команды подписки и управления
//! - **UDP сокеты** - для каждой подписки создается отдельный UDP сокет
//! - **Heartbeat** - механизм PING/PONG для контроля активности подписчика
//!
//! ## Протокол
//!
//! ### Команды через TCP
//!
//! - `STREAM <udp_address> <tickers>` - подписаться на котировки
//! - `STOP <udp_address>` - остановить поток котировок
//!
//! ### Heartbeat
//!
//! Клиент должен отправлять `PING` команды через интервал `PING_INTERVAL_SECONDS`.
//! Если в течение `PING_TIMEOUT_SECONDS` не поступило PING, сервер останавливает отправку котировок.
//!
//! ## Использование
//!
//! ```toml
//! [dependencies]
//! stock_stalker = { path = "..." }
//! ```
//!
//! ## Конфигурация
//!
//! - `PING_INTERVAL_SECONDS` (по умолчанию: 2) - интервал между PING командами
//! - `PING_TIMEOUT_SECONDS` (по умолчанию: 5) - таймаут без активности перед остановкой
//! - `GEN_QUOTE_RANGE_MIN` (по умолчанию: 100) - минимальное значение для генерации
//! - `GEN_QUOTE_RANGE_MAX` (по умолчанию: 500) - максимальное значение для генерации

pub mod quote;
pub mod protocol;
pub mod tickers;
pub mod error;

/// Интервал между PING командами в секундах (по умолчанию: 2)
pub const PING_INTERVAL_SECONDS: u8 = 2;

/// Таймаут без активности перед остановкой отправки котировок (по умолчанию: 5)
pub const PING_TIMEOUT_SECONDS: u8 = 5;

/// Минимальное значение для генерации котировок (по умолчанию: 100)
pub const GEN_QUOTE_RANGE_MIN: u16 = 100;

/// Максимальное значение для генерации котировок (по умолчанию: 500)
pub const GEN_QUOTE_RANGE_MAX: u16 = 500;
